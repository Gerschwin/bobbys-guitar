#!/usr/bin/env bash
# Builds the installable app from app.html (the single source file):
#   index.html - app.html wrapped in a full page with the app manifest and icons
#   sw.js      - offline cache, named after APP_VERSION so each release replaces the last
set -euo pipefail
cd "$(dirname "$0")"
VERSION=$(grep -oP "APP_VERSION = '\K[^']+" app.html)
{
  cat <<'HEAD'
<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="Learn guitar chords: big chord diagrams, hear each chord, check your playing with the mic, and strum along.">
<meta name="theme-color" content="#0B7A69">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/icon-192.png" type="image/png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Bobby’s Guitar">
<meta name="apple-mobile-web-app-status-bar-style" content="black">
HEAD
  sed -n '1,/^<\/style>/p' app.html
  printf '<style>body{margin:0}:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}[hidden]{display:none!important}</style></head><body>\n'
  sed -n '/^<\/style>/,$p' app.html | tail -n +2
  printf '</body></html>\n'
} > index.html
# songs/index.json lists every song file, so adding a song is just dropping a .json file in songs/
python3 - <<'PY'
import json, os
files = sorted(f for f in os.listdir('songs') if f.endswith('.json') and f != 'index.json')
for f in files: json.load(open(os.path.join('songs', f)))   # fail the build on a broken song file
json.dump({"songs": files}, open('songs/index.json', 'w'), indent=1)
print(f"{len(files)} songs indexed")
PY
SAMPLES=$(for m in $(seq 40 69); do printf "'samples/%s.mp3'," "$m"; done)
cat > sw.js <<SW
// Generated by build.sh - edit there. Version ${VERSION}.
const CACHE = 'bobbys-guitar-${VERSION}', FONTS = 'bobbys-guitar-fonts';
const CORE = ['./', 'index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png', ${SAMPLES%,}];
self.addEventListener('install', e => { self.skipWaiting(); e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE))); });
self.addEventListener('activate', e => e.waitUntil(
  caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE && k !== FONTS).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (req.mode === 'navigate'){
    // the page itself: always try the network first so updates show up, fall back to the cached copy offline
    e.respondWith(fetch(req).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put('./', c)); return r; })
      .catch(() => caches.match('./')));
  } else if (url.origin === location.origin && url.pathname.includes('/songs/')){
    // the song library: fetch fresh when online so new songs appear, cached copy offline
    e.respondWith(fetch(req).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put(req, c)); return r; }).catch(() => caches.match(req)));
  } else if (url.origin === location.origin){
    e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put(req, c)); return r; })));
  } else if (/fonts\.(googleapis|gstatic)\.com$/.test(url.hostname)){
    e.respondWith(caches.open(FONTS).then(x => x.match(req).then(hit => {
      const net = fetch(req).then(r => { x.put(req, r.clone()); return r; }).catch(() => hit);
      return hit || net;
    })));
  }
});
SW
echo "built v${VERSION}"
